#!/usr/bin/env node
// Generates the glyph roster for File → New Font from the Google Fonts
// glyphsets repo. GF_Latin_Core is the minimum set a family needs to be
// onboarded into Google Fonts, so it is what a new project starts with.
//
// The repo's .glyphs result file is the only artifact that carries names
// and codepoints together (the nice-names .txt has names only, the .nam
// has codepoints only), so that is what we read.
//
// Refresh with: pnpm run new-font-template

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const repoRoot = new URL("..", import.meta.url).pathname.replace(/\/$/, "");
const glyphsetsRoot =
  process.env.GF_GLYPHSETS_REPO ?? "/Users/eli/GF/repos/glyphsets";
const sourcePath = join(
  glyphsetsRoot,
  "data/results/glyphs/GF_Latin_Core.glyphs",
);
const outPath = join(repoRoot, "src/newFontTemplate.generated.ts");

const text = readFileSync(sourcePath, "utf8");

// Glyphs 3 source: each glyph is a `{ glyphname = X; ... }` block, with an
// optional decimal `unicode = N;`. Codepoints can also be a comma list on
// glyphs that carry more than one; we keep the first.
const glyphs = [];
for (const match of text.matchAll(/\{\s*glyphname = ([^;]+);(.*?)\n\},/gs)) {
  const name = match[1].trim().replace(/^"|"$/g, "");
  const body = match[2];
  const uni = body.match(/\n\s*unicode = ([^;]+);/);
  const first = uni?.[1]?.split(",")[0]?.trim();
  const codepoint = first ? Number.parseInt(first, 10) : NaN;
  glyphs.push({
    name,
    ...(Number.isFinite(codepoint)
      ? { unicode: codepoint.toString(16).toUpperCase().padStart(4, "0") }
      : {}),
  });
}

if (glyphs.length === 0) {
  console.error(`no glyphs parsed out of ${sourcePath}`);
  process.exit(1);
}

// .notdef must come first in the glyph order; the rest keep the order the
// glyphset defines.
glyphs.sort((a, b) =>
  a.name === ".notdef" ? -1 : b.name === ".notdef" ? 1 : 0,
);

const header =
  `// Generated by scripts/generate-new-font-template.mjs.\n` +
  `// Source: ${sourcePath}\n` +
  `// Do not edit by hand.\n\n`;

writeFileSync(
  outPath,
  `${header}export type TemplateGlyph = { name: string; unicode?: string };\n\n` +
    `export const GF_LATIN_CORE: TemplateGlyph[] = ${JSON.stringify(glyphs, null, 2)};\n`,
);

const encoded = glyphs.filter((g) => g.unicode).length;
console.log(
  `wrote ${outPath} (${glyphs.length} glyphs, ${encoded} encoded)`,
);
